using System.Text;
using ZoltDumpUI.Models;

namespace ZoltDumpUI.Services;

/// <summary>
/// Generates C++ SDK offset headers for Godot class definitions.
/// </summary>
public sealed class SdkExportService
{
    /// <summary>Generate a C++ header for a single class from LiveWalker fields.</summary>
    public string GenerateClassHeader(string className, string superName, List<LiveFieldValue> fields)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"// Auto-generated by Zolt-Dump");
        sb.AppendLine($"// Class: {className}");
        sb.AppendLine($"#pragma once");
        sb.AppendLine();

        var structName = className.Replace("::", "_");
        if (!string.IsNullOrEmpty(superName))
            sb.AppendLine($"struct {structName} : public {superName}");
        else
            sb.AppendLine($"struct {structName}");

        sb.AppendLine("{");

        int lastEnd = 0;
        foreach (var f in fields)
        {
            if (f.Offset > lastEnd)
            {
                sb.AppendLine($"    char _pad_0x{lastEnd:X}[0x{f.Offset - lastEnd:X}]; // 0x{lastEnd:X}");
            }
            var cppType = MapGodotToCppType(f.Type, f.Size);
            sb.AppendLine($"    {cppType} {SanitizeName(f.Name)}; // 0x{f.Offset:X} (Size: 0x{f.Size:X})");
            lastEnd = f.Offset + f.Size;
        }

        sb.AppendLine("};");
        return sb.ToString();
    }

    /// <summary>Generate a C++ header from ClassDB class info.</summary>
    public string GenerateClassHeaderFromSchema(ClassInfoModel classInfo)
    {
        return GenerateClassHeader(classInfo.ClassName, classInfo.SuperName,
            classInfo.Properties.Select(p => new LiveFieldValue
            {
                Name = p.Name,
                Type = p.Type,
                Offset = p.Offset,
                Size = p.Size
            }).ToList());
    }

    private static string MapGodotToCppType(string type, int size) => type switch
    {
        "BOOL" or "bool" => "bool",
        "INT" or "int" when size == 1 => "int8_t",
        "INT" or "int" when size == 2 => "int16_t",
        "INT" or "int" when size == 4 => "int32_t",
        "INT" or "int" => "int64_t",
        "real" => "double",                               // Godot 3.x real_t = always double
        "FLOAT" or "float" when size == 4 => "float",
        "FLOAT" or "float" => "double",
        "STRING" => "godot::String",
        "STRING_NAME" => "godot::StringName",
        "NODE_PATH" => "godot::NodePath",
        "VECTOR2" => "godot::Vector2",
        "VECTOR3" => "godot::Vector3",
        "VECTOR4" => "godot::Vector4",
        "COLOR" => "godot::Color",
        "QUATERNION" => "godot::Quaternion",
        "TRANSFORM2D" => "godot::Transform2D",
        "TRANSFORM3D" => "godot::Transform3D",
        "BASIS" => "godot::Basis",
        "AABB" => "godot::AABB",
        "RECT2" => "godot::Rect2",
        "PLANE" => "godot::Plane",
        "OBJECT" => "godot::Object*",
        "Quat" => "godot::Quat",                         // Godot 3.x
        "Transform" => "godot::Transform",               // Godot 3.x
        "ARRAY" or "Array" => "godot::Array",
        "DICTIONARY" or "Dictionary" => "godot::Dictionary",
        "PoolByteArray" => "godot::PoolByteArray",        // Godot 3.x Pool* types
        "PoolIntArray" => "godot::PoolIntArray",
        "PoolRealArray" => "godot::PoolRealArray",
        "PoolStringArray" => "godot::PoolStringArray",
        "PoolVector2Array" => "godot::PoolVector2Array",
        "PoolVector3Array" => "godot::PoolVector3Array",
        "PoolColorArray" => "godot::PoolColorArray",
        "PACKED_BYTE_ARRAY" => "godot::PackedByteArray",
        "PACKED_INT32_ARRAY" => "godot::PackedInt32Array",
        "PACKED_INT64_ARRAY" => "godot::PackedInt64Array",
        "PACKED_FLOAT32_ARRAY" => "godot::PackedFloat32Array",
        "PACKED_FLOAT64_ARRAY" => "godot::PackedFloat64Array",
        "PACKED_STRING_ARRAY" => "godot::PackedStringArray",
        "PACKED_VECTOR2_ARRAY" => "godot::PackedVector2Array",
        "PACKED_VECTOR3_ARRAY" => "godot::PackedVector3Array",
        "PACKED_COLOR_ARRAY" => "godot::PackedColorArray",
        "PACKED_VECTOR4_ARRAY" => "godot::PackedVector4Array",
        _ => $"uint8_t[0x{size:X}]"
    };

    private static string SanitizeName(string name)
    {
        if (string.IsNullOrEmpty(name)) return "_unnamed";
        var s = name.Replace(" ", "_").Replace("/", "_").Replace("-", "_");
        if (char.IsDigit(s[0])) s = "_" + s;
        return s;
    }
}
