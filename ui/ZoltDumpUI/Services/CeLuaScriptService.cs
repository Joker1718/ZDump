using System.Text;

namespace ZoltDumpUI.Services;

/// <summary>
/// Generates CE Lua Auto Assembler scripts for dynamic address resolution
/// via the Qual mailbox (g_zoltMailbox exported from proxy DLL).
/// Scripts survive game restarts — they resolve by node name + member name.
///
/// Two-step approach for GDScript members:
///   1. CMD_FIND_NODE → locate Object by scene tree node name (unique per sibling)
///   2. CMD_GET_MEMBER_ADDR → resolve GDScript member address using found objectAddr
///
/// This avoids the class name ambiguity problem (multiple objects share the same
/// native class like "Node2D" but have different node names like "Player", "Enemy").
/// </summary>
public sealed class CeLuaScriptService
{
    // Mailbox struct field offsets (must match Qual.h MailboxData)
    private const int OFF_CMD          = 0x000;
    private const int OFF_STATUS       = 0x004;
    private const int OFF_RESULT       = 0x008;
    private const int OFF_MEMBER_INDEX = 0x00C;
    private const int OFF_OBJECT_ADDR  = 0x010;
    private const int OFF_MEMBER_ADDR  = 0x018;
    private const int OFF_MEMBER_TYPE  = 0x020;
    private const int OFF_CLASS_NAME   = 0x028;
    private const int OFF_MEMBER_NAME  = 0x128;
    private const int OFF_NODE_NAME    = 0x228;
    private const int OFF_ERROR_MSG    = 0x328;
    private const int OFF_TARGET_OP    = 0x428;
    private const int OFF_TARGET_VALUE = 0x430;
    private const int OFF_FILTER_OP    = 0x438;
    private const int OFF_FILTER_VALUE = 0x440;
    private const int OFF_MATCH_STR    = 0x448;

    // FilterOp values (must match Qual::FilterOp)
    public const int FILTER_NONE = 0;
    public const int FILTER_GT   = 1;  // >
    public const int FILTER_LT   = 2;  // <
    public const int FILTER_NE   = 3;  // !=
    public const int FILTER_EQ   = 4;  // ==
    public const int FILTER_GE   = 5;  // >=
    public const int FILTER_LE   = 6;  // <=

    // Commands (must match Qual::Cmd)
    private const int CMD_IDLE                      = 0;
    private const int CMD_FIND_INSTANCE             = 1;
    private const int CMD_GET_MEMBER_ADDR           = 2;
    private const int CMD_FIND_NODE                 = 3;
    private const int CMD_FIND_INSTANCE_WITH_MEMBER = 4;
    private const int CMD_FIND_INSTANCE_BY_PATH     = 5;
    private const int CMD_FIND_MANAGED_INSTANCES    = 6;
    private const int CMD_RESOLVE_FIELD_OFFSET     = 7;

    // Results buffer offsets (must match ManagedSearchResults in Qual.h)
    private const int RES_COUNT    = 0x000;
    private const int RES_CAPACITY = 0x004;
    private const int RES_ENTRIES  = 0x008;
    private const int RES_ENTRY_SIZE = 16; // objectAddr(8) + managedAddr(8)

    // Status (must match Qual::Status)
    private const int STATUS_IDLE       = 0;
    private const int STATUS_DONE       = 1;
    private const int STATUS_PROCESSING = 2;
    private const int STATUS_INIT       = 0xFF;

    /// <summary>
    /// Generate a CE Lua AA script that resolves a GDScript member address
    /// via two-step mailbox communication:
    ///   Step 1: CMD_FIND_NODE → find Object by node name (e.g. "Main", "Player")
    ///   Step 2: CMD_GET_MEMBER_ADDR → resolve member using found objectAddr
    ///
    /// This approach handles duplicate class names (Player HP vs Enemy HP) because
    /// node names are unique among siblings in Godot's scene tree.
    /// </summary>
    /// <param name="nodeName">Scene tree node name (e.g. "Main", "Player")</param>
    /// <param name="memberName">GDScript member name (e.g. "JarMoney", "HP")</param>
    /// <param name="symbolName">CE symbol name to register (defaults to NodeName_MemberName)</param>
    /// <returns>Complete AA script with [ENABLE]/[DISABLE] sections</returns>
    public string GenerateMemberScript(string nodeName, string memberName,
        string? symbolName = null, string? containerKey = null)
    {
        symbolName ??= SanitizeSymbolName($"{nodeName}_{memberName}");
        bool hasKey = !string.IsNullOrEmpty(containerKey);
        string displayTarget = hasKey ? $"{memberName}[{containerKey}]" : memberName;

        var sb = new StringBuilder();
        sb.AppendLine("[ENABLE]");
        sb.AppendLine("{$lua}");
        sb.AppendLine($"-- ZoltDump: Resolve '{nodeName}.{displayTarget}' via proxy DLL mailbox");
        if (hasKey)
            sb.AppendLine($"-- Three-step: FIND_NODE → GET_MEMBER_ADDR + dict/array key (survives game restarts)");
        else
            sb.AppendLine("-- Two-step: FIND_NODE → GET_MEMBER_ADDR (survives game restarts)");
        sb.AppendLine("-- Generated by ZoltDumpUI");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        EmitCloseLuaEngineDef(sb);

        // ── Editable container key at the top (if applicable) ──
        if (hasKey)
        {
            sb.AppendLine("-- ═══ Container key (edit this to target a different dict key / array index) ═══");
            sb.AppendLine($"local container_key = '{EscapeLua(containerKey!)}'");
            sb.AppendLine();
        }

        // ── Mailbox init check ──
        EmitMailboxInit(sb);

        // ── Step 1: CMD_FIND_NODE ──
        sb.AppendLine("-- ═══ Step 1: Find node by name ═══");
        sb.AppendLine($"writeString(mb + 0x{OFF_NODE_NAME:X}, '{EscapeLua(nodeName)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_NODE_NAME:X} + {nodeName.Length}, 0)");
        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0)  -- clear previous");
        EmitTriggerAndPoll(sb, CMD_FIND_NODE, "FIND_NODE");
        sb.AppendLine();

        sb.AppendLine($"local objAddr = readQword(mb + 0x{OFF_OBJECT_ADDR:X})");
        sb.AppendLine("if objAddr == 0 then");
        sb.AppendLine($"  error('[ZoltDump] Node \\'{nodeName}\\' not found in scene tree')");
        sb.AppendLine("end");
        sb.AppendLine($"print(string.format('[ZoltDump] Found node \\'{nodeName}\\' @ %X', objAddr))");
        sb.AppendLine();

        // ── Step 2: CMD_GET_MEMBER_ADDR (with optional dict/array key via matchStr) ──
        if (hasKey)
            sb.AppendLine($"-- ═══ Step 2: Resolve member '{memberName}' then lookup key '{containerKey}' ═══");
        else
            sb.AppendLine("-- ═══ Step 2: Resolve member address ═══");
        sb.AppendLine($"-- objectAddr is already set from Step 1 (DLL keeps it)");
        sb.AppendLine($"writeString(mb + 0x{OFF_MEMBER_NAME:X}, '{EscapeLua(memberName)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_MEMBER_NAME:X} + {memberName.Length}, 0)");

        // Write container key to matchStr field if present
        if (hasKey)
        {
            sb.AppendLine($"writeString(mb + 0x{OFF_MATCH_STR:X}, container_key)");
            sb.AppendLine($"writeByte(mb + 0x{OFF_MATCH_STR:X} + #container_key, 0)");
        }
        else
        {
            sb.AppendLine($"writeByte(mb + 0x{OFF_MATCH_STR:X}, 0)  -- no container key");
        }

        sb.AppendLine($"writeQword(mb + 0x{OFF_MEMBER_ADDR:X}, 0)  -- clear previous");
        EmitTriggerAndPoll(sb, CMD_GET_MEMBER_ADDR, "GET_MEMBER_ADDR");
        sb.AppendLine();

        sb.AppendLine($"local addr = readQword(mb + 0x{OFF_MEMBER_ADDR:X})");
        sb.AppendLine("if addr ~= 0 then");
        sb.AppendLine($"  unregisterSymbol('{symbolName}')");
        sb.AppendLine($"  registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"  print(string.format('[ZoltDump] {symbolName} = %X', addr))");
        sb.AppendLine("  closeLuaEngine()");
        sb.AppendLine("else");
        sb.AppendLine($"  print('[ZoltDump] WARNING: {displayTarget} address is 0')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine($"print('[ZoltDump] {symbolName} symbol removed')");
        sb.AppendLine("closeLuaEngine()");

        return sb.ToString();
    }

    /// <summary>
    /// Generate a CE Lua AA script for a native property with known offset on a Node.
    ///   Step 1: CMD_FIND_NODE → find Object by node name
    ///   Step 2: Register symbol at objAddr + offset
    ///
    /// Use this for native engine properties (e.g. Timer.time_left, Node2D.position)
    /// that have a fixed offset from the Object base — NOT GDScript members.
    /// </summary>
    /// <param name="nodeName">Scene tree node name (e.g. "WaveTimer")</param>
    /// <param name="memberName">Native property name for display (e.g. "time_left")</param>
    /// <param name="offset">Byte offset from Object base (e.g. 0x1E0)</param>
    /// <param name="symbolName">CE symbol name to register</param>
    /// <returns>Complete AA script with [ENABLE]/[DISABLE] sections</returns>
    public string GenerateNativeOffsetScript(string nodeName, string memberName, int offset, string? symbolName = null)
    {
        symbolName ??= SanitizeSymbolName($"{nodeName}_{memberName}");

        var sb = new StringBuilder();
        sb.AppendLine("[ENABLE]");
        sb.AppendLine("{$lua}");
        sb.AppendLine($"-- ZoltDump: Resolve '{nodeName}.{memberName}' (native offset +0x{offset:X})");
        sb.AppendLine("-- FIND_NODE + fixed offset (survives game restarts)");
        sb.AppendLine("-- Generated by ZoltDumpUI");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        EmitCloseLuaEngineDef(sb);

        // ── Mailbox init check ──
        EmitMailboxInit(sb);

        // ── Step 1: CMD_FIND_NODE ──
        sb.AppendLine("-- ═══ Step 1: Find node by name ═══");
        sb.AppendLine($"writeString(mb + 0x{OFF_NODE_NAME:X}, '{EscapeLua(nodeName)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_NODE_NAME:X} + {nodeName.Length}, 0)");
        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0)  -- clear previous");
        EmitTriggerAndPoll(sb, CMD_FIND_NODE, "FIND_NODE");
        sb.AppendLine();

        sb.AppendLine($"local objAddr = readQword(mb + 0x{OFF_OBJECT_ADDR:X})");
        sb.AppendLine("if objAddr == 0 then");
        sb.AppendLine($"  error('[ZoltDump] Node \\'{nodeName}\\' not found in scene tree')");
        sb.AppendLine("end");
        sb.AppendLine($"print(string.format('[ZoltDump] Found node \\'{nodeName}\\' @ %X', objAddr))");
        sb.AppendLine();

        // ── Step 2: Apply offset directly ──
        sb.AppendLine($"-- ═══ Step 2: Apply native offset +0x{offset:X} ═══");
        sb.AppendLine($"local addr = objAddr + 0x{offset:X}");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine($"registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"print(string.format('[ZoltDump] {symbolName} = %X (obj+0x{offset:X})', addr))");
        sb.AppendLine("closeLuaEngine()");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine($"print('[ZoltDump] {symbolName} symbol removed')");
        sb.AppendLine("closeLuaEngine()");

        return sb.ToString();
    }

    /// <summary>
    /// Generate a CE Lua AA script that resolves a GDScript member address
    /// for non-Node objects (e.g. Reference, Resource) using a known object address:
    ///   Step 1: Write known objectAddr directly to mailbox
    ///   Step 2: CMD_GET_MEMBER_ADDR → resolve member using that address
    ///
    /// Use this for objects that are NOT in the scene tree (Reference, Resource, etc.).
    /// Note: Address is session-specific — script won't survive game restarts.
    /// For Node-derived objects, use <see cref="GenerateMemberScript"/> instead.
    /// </summary>
    /// <param name="objectAddress">Known object address (hex string, e.g. "1CB6AF05DD0")</param>
    /// <param name="className">Godot class name for display (e.g. "Reference")</param>
    /// <param name="memberName">GDScript member name (e.g. "money", "hp")</param>
    /// <param name="symbolName">CE symbol name to register</param>
    /// <returns>Complete AA script with [ENABLE]/[DISABLE] sections</returns>
    public string GenerateDirectMemberScript(string objectAddress, string className, string memberName, string? symbolName = null)
    {
        symbolName ??= SanitizeSymbolName($"{className}_{memberName}");

        var sb = new StringBuilder();
        sb.AppendLine("[ENABLE]");
        sb.AppendLine("{$lua}");
        sb.AppendLine($"-- ZoltDump: Resolve '{className}.{memberName}' via proxy DLL mailbox");
        sb.AppendLine($"-- Direct address: 0x{objectAddress} (session-specific, won't survive restarts)");
        sb.AppendLine("-- Generated by ZoltDumpUI");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        EmitCloseLuaEngineDef(sb);

        // ── Mailbox init check ──
        EmitMailboxInit(sb);

        // ── Write known object address directly ──
        sb.AppendLine($"-- ═══ Set known object address (non-Node: {className}) ═══");
        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0x{objectAddress})");
        sb.AppendLine($"print(string.format('[ZoltDump] Using {className} @ 0x{objectAddress}'))");
        sb.AppendLine();

        // ── CMD_GET_MEMBER_ADDR ──
        sb.AppendLine("-- ═══ Resolve member address ═══");
        sb.AppendLine($"writeString(mb + 0x{OFF_MEMBER_NAME:X}, '{EscapeLua(memberName)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_MEMBER_NAME:X} + {memberName.Length}, 0)");
        sb.AppendLine($"writeByte(mb + 0x{OFF_MATCH_STR:X}, 0)  -- no container key");
        sb.AppendLine($"writeQword(mb + 0x{OFF_MEMBER_ADDR:X}, 0)  -- clear previous");
        EmitTriggerAndPoll(sb, CMD_GET_MEMBER_ADDR, "GET_MEMBER_ADDR");
        sb.AppendLine();

        sb.AppendLine($"local addr = readQword(mb + 0x{OFF_MEMBER_ADDR:X})");
        sb.AppendLine("if addr ~= 0 then");
        sb.AppendLine($"  unregisterSymbol('{symbolName}')");
        sb.AppendLine($"  registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"  print(string.format('[ZoltDump] {symbolName} = %X', addr))");
        sb.AppendLine("  closeLuaEngine()");
        sb.AppendLine("else");
        sb.AppendLine($"  print('[ZoltDump] WARNING: {memberName} address is 0')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine($"print('[ZoltDump] {symbolName} symbol removed')");
        sb.AppendLine("closeLuaEngine()");

        return sb.ToString();
    }

    /// <summary>
    /// Generate a CE Lua AA script that finds a specific Object instance by class name
    /// that has a particular GDScript member, then resolves that member's address.
    /// Single-step: CMD_FIND_INSTANCE_WITH_MEMBER (className + memberName → objectAddr + memberAddr).
    ///
    /// This solves the "509 Reference objects" problem — instead of finding the first Reference,
    /// it finds the one that actually has a "gold" member. Survives game restarts.
    ///
    /// When multiple objects share the same member name (e.g. multiple "gold"), use
    /// <paramref name="criteria"/> to set value-based filters for disambiguation.
    /// </summary>
    /// <param name="className">Godot class name (e.g. "Reference")</param>
    /// <param name="memberName">GDScript member name (e.g. "gold")</param>
    /// <param name="criteria">Optional value criteria for disambiguation</param>
    /// <param name="symbolName">CE symbol name to register</param>
    /// <returns>Complete AA script with [ENABLE]/[DISABLE] sections</returns>
    public string GenerateFindInstanceMemberScript(string className, string memberName,
        Models.MemberFilterCriteria? criteria = null, string? symbolName = null,
        string? containerKey = null)
    {
        symbolName ??= SanitizeSymbolName($"{className}_{memberName}");
        string? filterMemberName = criteria?.FilterMember;
        bool hasFilter = !string.IsNullOrEmpty(filterMemberName);
        bool hasTargetCriteria = criteria is not null && criteria.TargetOp != FILTER_NONE;
        bool hasFilterCriteria = criteria is not null && criteria.FilterOp != FILTER_NONE && hasFilter;
        bool hasKey = !string.IsNullOrEmpty(containerKey);

        string displayTarget = hasKey ? $"{memberName}[{containerKey}]" : memberName;

        var sb = new StringBuilder();
        sb.AppendLine("[ENABLE]");
        sb.AppendLine("{$lua}");
        if (hasKey)
            sb.AppendLine($"-- ZoltDump: Find '{className}' with member '{memberName}', key '{containerKey}'");
        else
            sb.AppendLine($"-- ZoltDump: Find '{className}' with member '{memberName}' via proxy DLL mailbox");
        sb.AppendLine("-- Single-step: FIND_INSTANCE_WITH_MEMBER (survives game restarts)");
        sb.AppendLine("-- Generated by ZoltDumpUI");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        EmitCloseLuaEngineDef(sb);

        // ── Editable container key at the top (if applicable) ──
        if (hasKey)
        {
            sb.AppendLine("-- ═══ Container key (edit this to target a different dict key / array index) ═══");
            sb.AppendLine($"local container_key = '{EscapeLua(containerKey!)}'");
            sb.AppendLine();
        }

        // ── Editable criteria at the top of the script ──
        sb.AppendLine("-- ═══ Criteria (edit these to fine-tune which instance is found) ═══");
        sb.AppendLine($"-- FILTER_NONE=0, GT=1, LT=2, NE=3, EQ=4, GE=5, LE=6");
        if (hasTargetCriteria)
        {
            sb.AppendLine($"local target_op    = {criteria!.TargetOp}   -- {FormatFilterOp(criteria.TargetOp)} (for '{memberName}')");
            sb.AppendLine($"local target_value = {criteria.TargetValue}   -- {memberName} {FormatFilterOpSymbol(criteria.TargetOp)} {criteria.TargetValue}");
        }
        else
        {
            sb.AppendLine($"local target_op    = 0   -- no value filter on '{memberName}'");
            sb.AppendLine($"local target_value = 0");
        }

        if (hasFilterCriteria)
        {
            sb.AppendLine($"local filter_op    = {criteria!.FilterOp}   -- {FormatFilterOp(criteria.FilterOp)} (for '{filterMemberName}')");
            sb.AppendLine($"local filter_value = {criteria.FilterValue}   -- {filterMemberName} {FormatFilterOpSymbol(criteria.FilterOp)} {criteria.FilterValue}");
        }
        else
        {
            sb.AppendLine($"local filter_op    = 0   -- no value filter on secondary member");
            sb.AppendLine($"local filter_value = 0");
        }
        sb.AppendLine();

        // ── Mailbox init check ──
        EmitMailboxInit(sb);

        // ── CMD_FIND_INSTANCE_WITH_MEMBER ──
        if (hasKey)
            sb.AppendLine($"-- ═══ Find {className} with '{memberName}' → key '{containerKey}' ═══");
        else if (hasFilter)
            sb.AppendLine($"-- ═══ Find {className} with '{memberName}' + '{filterMemberName}' ═══");
        else
            sb.AppendLine($"-- ═══ Find {className} instance with member '{memberName}' ═══");

        sb.AppendLine($"writeString(mb + 0x{OFF_CLASS_NAME:X}, '{EscapeLua(className)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_CLASS_NAME:X} + {className.Length}, 0)");
        sb.AppendLine($"writeString(mb + 0x{OFF_MEMBER_NAME:X}, '{EscapeLua(memberName)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_MEMBER_NAME:X} + {memberName.Length}, 0)");

        // Secondary filter member (written to nodeName field, repurposed for non-Node commands)
        if (hasFilter)
        {
            sb.AppendLine($"writeString(mb + 0x{OFF_NODE_NAME:X}, '{EscapeLua(filterMemberName!)}')");
            sb.AppendLine($"writeByte(mb + 0x{OFF_NODE_NAME:X} + {filterMemberName!.Length}, 0)");
        }
        else
        {
            sb.AppendLine($"writeByte(mb + 0x{OFF_NODE_NAME:X}, 0)  -- no secondary filter member");
        }

        // Value criteria
        sb.AppendLine($"writeInteger(mb + 0x{OFF_TARGET_OP:X}, target_op)");
        sb.AppendLine($"writeQword(mb + 0x{OFF_TARGET_VALUE:X}, target_value)");
        sb.AppendLine($"writeInteger(mb + 0x{OFF_FILTER_OP:X}, filter_op)");
        sb.AppendLine($"writeQword(mb + 0x{OFF_FILTER_VALUE:X}, filter_value)");

        // Container key via matchStr (for dict key / array index lookup after member resolution)
        if (hasKey)
        {
            sb.AppendLine($"writeString(mb + 0x{OFF_MATCH_STR:X}, container_key)");
            sb.AppendLine($"writeByte(mb + 0x{OFF_MATCH_STR:X} + #container_key, 0)");
        }
        else
        {
            sb.AppendLine($"writeByte(mb + 0x{OFF_MATCH_STR:X}, 0)  -- no container key");
        }

        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0)  -- clear previous");
        sb.AppendLine($"writeQword(mb + 0x{OFF_MEMBER_ADDR:X}, 0)  -- clear previous");
        EmitTriggerAndPoll(sb, CMD_FIND_INSTANCE_WITH_MEMBER, "FIND_INSTANCE_WITH_MEMBER");
        sb.AppendLine();

        sb.AppendLine($"local objAddr = readQword(mb + 0x{OFF_OBJECT_ADDR:X})");
        sb.AppendLine($"local addr = readQword(mb + 0x{OFF_MEMBER_ADDR:X})");
        sb.AppendLine("if addr ~= 0 then");
        sb.AppendLine($"  unregisterSymbol('{symbolName}')");
        sb.AppendLine($"  registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"  print(string.format('[ZoltDump] {symbolName} = %X (obj @ %X)', addr, objAddr))");
        sb.AppendLine("  closeLuaEngine()");
        sb.AppendLine("else");
        sb.AppendLine($"  print('[ZoltDump] WARNING: {displayTarget} address is 0')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine($"print('[ZoltDump] {symbolName} symbol removed')");
        sb.AppendLine("closeLuaEngine()");

        return sb.ToString();
    }

    /// <summary>Format FilterOp as human-readable name.</summary>
    private static string FormatFilterOp(int op) => op switch
    {
        FILTER_GT => "GT (>)",
        FILTER_LT => "LT (<)",
        FILTER_NE => "NE (!=)",
        FILTER_EQ => "EQ (==)",
        FILTER_GE => "GE (>=)",
        FILTER_LE => "LE (<=)",
        _ => "NONE"
    };

    /// <summary>Format FilterOp as operator symbol.</summary>
    private static string FormatFilterOpSymbol(int op) => op switch
    {
        FILTER_GT => ">",
        FILTER_LT => "<",
        FILTER_NE => "!=",
        FILTER_EQ => "==",
        FILTER_GE => ">=",
        FILTER_LE => "<=",
        _ => "?"
    };

