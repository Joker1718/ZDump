    /// <summary>
    /// Generate a CE Lua AA script that finds an Object instance by class name.
    /// Use this for native Godot objects (not GDScript nodes).
    /// </summary>
    public string GenerateFindInstanceScript(string className, string? symbolName = null)
    {
        symbolName ??= SanitizeSymbolName(className);

        var sb = new StringBuilder();
        sb.AppendLine("[ENABLE]");
        sb.AppendLine("{$lua}");
        sb.AppendLine($"-- ZoltDump: Find instance of '{className}' via proxy DLL mailbox");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        EmitCloseLuaEngineDef(sb);

        EmitMailboxInit(sb);

        sb.AppendLine($"writeString(mb + 0x{OFF_CLASS_NAME:X}, '{EscapeLua(className)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_CLASS_NAME:X} + {className.Length}, 0)");
        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0)");
        EmitTriggerAndPoll(sb, CMD_FIND_INSTANCE, "FIND_INSTANCE");
        sb.AppendLine();

        sb.AppendLine($"local addr = readQword(mb + 0x{OFF_OBJECT_ADDR:X})");
        sb.AppendLine("if addr ~= 0 then");
        sb.AppendLine($"  unregisterSymbol('{symbolName}')");
        sb.AppendLine($"  registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"  print(string.format('[ZoltDump] {symbolName} = %X', addr))");
        sb.AppendLine("  closeLuaEngine()");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine("closeLuaEngine()");

        return sb.ToString();
    }

    /// <summary>
    /// Generate a CE Lua AA script that finds a specific Object instance by
    /// walking a dot-separated property path and matching a string value, then
    /// resolves a target member address on the found instance.
    ///
    /// Single-step: CMD_FIND_INSTANCE_BY_PATH (survives game restarts).
    ///
    /// Example: Find the InventoryElement whose item.my_id == "item_tree",
    /// then resolve "current_number" on it.
    /// </summary>
    /// <param name="className">Godot class name filter (e.g. "Button"), or empty for any class</param>
    /// <param name="matchPath">Dot-separated property path (e.g. "item.my_id")</param>
    /// <param name="matchValue">Expected string value at end of path (e.g. "item_tree")</param>
    /// <param name="memberName">Member to resolve on found instance (e.g. "current_number")</param>
    /// <param name="symbolName">CE symbol name to register</param>
    /// <returns>Complete AA script with [ENABLE]/[DISABLE] sections</returns>
    public string GenerateFindInstanceByPathScript(string className, string matchPath,
        string matchValue, string memberName, string? symbolName = null)
    {
        symbolName ??= SanitizeSymbolName($"{matchValue}_{memberName}");

        var sb = new StringBuilder();
        sb.AppendLine("[ENABLE]");
        sb.AppendLine("{$lua}");
        sb.AppendLine($"-- ZoltDump: Find instance where {matchPath} == '{matchValue}', resolve '{memberName}'");
        sb.AppendLine("-- Single-step: FIND_INSTANCE_BY_PATH (survives game restarts)");
        sb.AppendLine("-- Generated by ZoltDumpUI");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        EmitCloseLuaEngineDef(sb);

        // ── Editable search criteria at the top ──
        sb.AppendLine("-- ═══ Search criteria (edit these to find a different instance) ═══");
        sb.AppendLine($"local match_path  = '{EscapeLua(matchPath)}'   -- property path to check");
        sb.AppendLine($"local match_value = '{EscapeLua(matchValue)}'   -- expected value");
        sb.AppendLine();

        // ── Mailbox init check ──
        EmitMailboxInit(sb);

        // ── CMD_FIND_INSTANCE_BY_PATH ──
        sb.AppendLine($"-- ═══ Find instance where {matchPath} == '{matchValue}' ═══");
        if (!string.IsNullOrEmpty(className))
        {
            sb.AppendLine($"writeString(mb + 0x{OFF_CLASS_NAME:X}, '{EscapeLua(className)}')");
            sb.AppendLine($"writeByte(mb + 0x{OFF_CLASS_NAME:X} + {className.Length}, 0)");
        }
        else
        {
            sb.AppendLine($"writeByte(mb + 0x{OFF_CLASS_NAME:X}, 0)  -- no class filter");
        }

        sb.AppendLine($"writeString(mb + 0x{OFF_MEMBER_NAME:X}, '{EscapeLua(memberName)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_MEMBER_NAME:X} + {memberName.Length}, 0)");
        sb.AppendLine($"writeString(mb + 0x{OFF_NODE_NAME:X}, match_path)");
        sb.AppendLine($"writeByte(mb + 0x{OFF_NODE_NAME:X} + #match_path, 0)");
        sb.AppendLine($"writeString(mb + 0x{OFF_MATCH_STR:X}, match_value)");
        sb.AppendLine($"writeByte(mb + 0x{OFF_MATCH_STR:X} + #match_value, 0)");

        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0)  -- clear previous");
        sb.AppendLine($"writeQword(mb + 0x{OFF_MEMBER_ADDR:X}, 0)  -- clear previous");
        EmitTriggerAndPoll(sb, CMD_FIND_INSTANCE_BY_PATH, "FIND_INSTANCE_BY_PATH");
        sb.AppendLine();

        sb.AppendLine($"local objAddr = readQword(mb + 0x{OFF_OBJECT_ADDR:X})");
        sb.AppendLine($"local addr = readQword(mb + 0x{OFF_MEMBER_ADDR:X})");
        sb.AppendLine("if addr ~= 0 then");
        sb.AppendLine($"  unregisterSymbol('{symbolName}')");
        sb.AppendLine($"  registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"  print(string.format('[ZoltDump] {symbolName} = %X (obj @ %X)', addr, objAddr))");
        sb.AppendLine("  closeLuaEngine()");
        sb.AppendLine("else");
        sb.AppendLine($"  print('[ZoltDump] WARNING: {memberName} address is 0')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine($"print('[ZoltDump] {symbolName} symbol removed')");
        sb.AppendLine("closeLuaEngine()");

        return sb.ToString();
    }

    /// <summary>
    /// Generate a CE Lua AA script for .NET managed object field(s) using
    /// CMD_FIND_MANAGED_INSTANCES (bulk DLL-side scan).
    ///
    /// Single mode: Finds first matching managed object, registers symbol at managed+offset.
    /// Multi mode:  Finds ALL matching managed objects, creates CE memory records as children
    ///              of a parent group header in the CE address list.
    ///
    /// The DLL handles: ObjectDB iteration → class filter → MethodTable filter →
    /// CSharpInstance chain → GCHandle → managed field filter. Results stored in
    /// g_zoltManagedResults buffer (up to 256 entries).
    /// </summary>
    /// <param name="className">Godot class name filter (e.g. "Control")</param>
    /// <param name="criteria">Managed filter criteria with offsets and FindAll mode</param>
    /// <param name="symbolName">CE symbol name (single mode) or prefix (multi mode)</param>
    /// <param name="fieldDisplayName">Display name for the field (e.g. "+0x84")</param>
    /// <param name="methodTableHex">Optional .NET MethodTable hex value for type matching (e.g. "7FF7D90BE0F8")</param>
    /// <returns>Complete AA script with [ENABLE]/[DISABLE] sections</returns>
    public string GenerateManagedInstanceScript(string className,
        Models.MemberFilterCriteria criteria, string symbolName, string fieldDisplayName,
        string? methodTableHex = null, string? nodeName = null,
        int l2ChildRefOffset = -1)
    {
        int targetOffset = criteria.TargetFieldOffset;
        int filterOffset = criteria.FilterFieldOffset;
        int filterOp = (filterOffset >= 0) ? criteria.FilterOp : FILTER_NONE;
        long filterValue = criteria.FilterValue;
        int filterSize = criteria.FilterFieldSize;
        bool findAll = criteria.FindAll;
        bool hasMT = !string.IsNullOrEmpty(methodTableHex);

        // Include filter criteria in description so different filters get separate groups
        // e.g. "+Control .NET managed +0x84 [+0x8C==1] (do not delete this)"
        string filterTag = (filterOffset >= 0 && filterOp != FILTER_NONE)
            ? $" [+0x{filterOffset:X}{FormatFilterOpSymbol(filterOp)}{filterValue}]"
            : "";
        string parentDesc = $"+{className} .NET managed +0x{targetOffset:X}{filterTag} (do not delete this)";

        var sb = new StringBuilder();
        sb.AppendLine("[ENABLE]");
        sb.AppendLine("{$lua}");
        if (findAll)
            sb.AppendLine($"-- ZoltDump: Find ALL '{className}' .NET managed objects with field +0x{targetOffset:X}");
        else
            sb.AppendLine($"-- ZoltDump: Find '{className}' .NET managed object, field +0x{targetOffset:X}");
        sb.AppendLine("-- CMD_FIND_MANAGED_INSTANCES (DLL-side bulk scan, ~500ms)");
        sb.AppendLine("-- Generated by ZoltDumpUI");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        EmitCloseLuaEngineDef(sb);

        // ── Editable configuration at the top ──
        sb.AppendLine("-- ═══ Configuration (edit these for your game) ═══");
        sb.AppendLine($"local godot_class     = '{EscapeLua(className)}'   -- Godot base class to search");
        sb.AppendLine($"local target_offset   = 0x{targetOffset:X}         -- managed field offset for target (fallback)");
        // Node name filter — narrows scan to Godot nodes whose name contains this substring.
        // Prevents unrelated nodes (Game, HealthBar) from polluting auto-discover MT.
        if (!string.IsNullOrEmpty(nodeName))
            sb.AppendLine($"local node_name       = '{EscapeLua(nodeName)}'    -- Godot node name filter (substring match)");
        else
            sb.AppendLine($"local node_name       = ''                         -- no node name filter");
        sb.AppendLine("-- MethodTable: filters to exact .NET type. Changes every game restart.");
        sb.AppendLine("-- Clear to auto-discover from first match, or set manually if wrong type.");
        if (hasMT)
            sb.AppendLine($"local method_table    = '{methodTableHex}'  -- .NET child type MT (changes per restart)");
        else
            sb.AppendLine($"local method_table    = ''  -- auto-discover from first match");
        if (filterOffset >= 0)
        {
            sb.AppendLine($"local filter_offset   = 0x{filterOffset:X}         -- managed field offset for filter (fallback)");
            sb.AppendLine($"local filter_op       = {filterOp}              -- {FormatFilterOp(filterOp)}");
            sb.AppendLine($"local filter_value    = {filterValue}           -- comparison value");
            sb.AppendLine($"local filter_size     = {filterSize}            -- read size in bytes (4=int32, 8=int64)");
        }
        else
        {
            sb.AppendLine($"local filter_offset   = -1           -- no filter (-1 = disabled)");
            sb.AppendLine($"local filter_op       = 0            -- FILTER_NONE");
            sb.AppendLine($"local filter_value    = 0");
            sb.AppendLine($"local filter_size     = 4");
        }
        // L2 child reference offset: when data lives in a nested child managed object
        // (not directly in the wrapper), this tells the DLL which wrapper field offset
        // to follow. -1 = auto-scan all offsets (default for L1/simple L2).
        if (l2ChildRefOffset >= 8)
            sb.AppendLine($"local l2_child_ref    = 0x{l2ChildRefOffset:X}       -- wrapper field offset to child managed object");
        else
            sb.AppendLine($"local l2_child_ref    = 0             -- 0 = auto-scan wrapper refs (no specific hint)");

        // .NET reflection info — resolves field names to offsets at runtime.
        // When present, the script survives game updates that change field layouts.
        string dotNetType = criteria.DotNetTypeName;
        string targetFieldName = criteria.TargetFieldName;
        string filterFieldName = criteria.FilterFieldName;
        bool hasReflection = !string.IsNullOrEmpty(dotNetType) &&
                             !string.IsNullOrEmpty(targetFieldName);
        if (hasReflection)
        {
            sb.AppendLine();
            sb.AppendLine("-- .NET reflection: resolve field offsets by name at runtime.");
            sb.AppendLine("-- Survives game updates that change field layouts but keep the same names.");
            sb.AppendLine($"local dotnet_type      = '{EscapeLua(dotNetType)}'");
            sb.AppendLine($"local target_field     = '{EscapeLua(targetFieldName)}'");
            if (!string.IsNullOrEmpty(filterFieldName))
                sb.AppendLine($"local filter_field     = '{EscapeLua(filterFieldName)}'");
            else
                sb.AppendLine($"local filter_field     = ''  -- no reflection for filter");
        }
        sb.AppendLine();

        // ── Mailbox + results buffer init ──
        EmitMailboxInit(sb);
        sb.AppendLine("local resBuf = getAddress('g_zoltManagedResults')");
        sb.AppendLine("if resBuf == 0 or resBuf == nil then");
        sb.AppendLine("  error('[ZoltDump] g_zoltManagedResults not found — DLL too old')");
        sb.AppendLine("end");

        // ── Resolve field offsets via CMD_RESOLVE_FIELD_OFFSET ──
        if (hasReflection)
        {
            sb.AppendLine();
            EmitResolveFieldOffset(sb, filterFieldName);
        }
        sb.AppendLine();

        // ── CMD_FIND_MANAGED_INSTANCES ──
        sb.AppendLine("-- ═══ Send bulk scan command ═══");
        sb.AppendLine($"writeString(mb + 0x{OFF_CLASS_NAME:X}, godot_class)");
        sb.AppendLine($"writeByte(mb + 0x{OFF_CLASS_NAME:X} + #godot_class, 0)");
        sb.AppendLine();

        // Node name filter via memberName field
        sb.AppendLine("-- Node name filter: narrows to Godot nodes matching this name (substring)");
        sb.AppendLine("if #node_name > 0 then");
        sb.AppendLine($"  writeString(mb + 0x{OFF_MEMBER_NAME:X}, node_name)");
        sb.AppendLine($"  writeByte(mb + 0x{OFF_MEMBER_NAME:X} + #node_name, 0)");
        sb.AppendLine("else");
        sb.AppendLine($"  writeByte(mb + 0x{OFF_MEMBER_NAME:X}, 0)  -- no node name filter");
        sb.AppendLine("end");
        sb.AppendLine();

        // MethodTable type filter via nodeName field
        sb.AppendLine("-- MethodTable filter: only match objects with same .NET type");
        sb.AppendLine("if #method_table > 0 then");
        sb.AppendLine($"  writeString(mb + 0x{OFF_NODE_NAME:X}, method_table)");
        sb.AppendLine($"  writeByte(mb + 0x{OFF_NODE_NAME:X} + #method_table, 0)");
        sb.AppendLine("else");
        sb.AppendLine($"  writeByte(mb + 0x{OFF_NODE_NAME:X}, 0)  -- no MT filter");
        sb.AppendLine("end");
        sb.AppendLine();

        sb.AppendLine("-- targetOp + targetValue = managed field filter (applied DLL-side)");
        sb.AppendLine("if filter_offset >= 0 then");
        sb.AppendLine($"  writeInteger(mb + 0x{OFF_TARGET_OP:X}, filter_op)");
        sb.AppendLine($"  writeQword(mb + 0x{OFF_TARGET_VALUE:X}, filter_value)");
        sb.AppendLine($"  writeInteger(mb + 0x{OFF_FILTER_OP:X}, filter_offset)    -- repurposed: managed field offset");
        sb.AppendLine($"  writeQword(mb + 0x{OFF_FILTER_VALUE:X}, filter_size)     -- repurposed: read size");
        sb.AppendLine("else");
        sb.AppendLine($"  writeInteger(mb + 0x{OFF_TARGET_OP:X}, 0)   -- FILTER_NONE");
        sb.AppendLine($"  writeQword(mb + 0x{OFF_TARGET_VALUE:X}, 0)");
        sb.AppendLine($"  writeInteger(mb + 0x{OFF_FILTER_OP:X}, 0)");
        sb.AppendLine($"  writeQword(mb + 0x{OFF_FILTER_VALUE:X}, 4)");
        sb.AppendLine("end");
        sb.AppendLine();
        // L2 child ref offset hint (memberIndex field, 0x00C)
        sb.AppendLine("-- L2 child ref: tells DLL which wrapper offset to follow for nested child");
        sb.AppendLine($"writeInteger(mb + 0x{OFF_MEMBER_INDEX:X}, l2_child_ref)");
        sb.AppendLine();
        EmitTriggerAndPoll(sb, CMD_FIND_MANAGED_INSTANCES, "FIND_MANAGED_INSTANCES", resultIsCount: true);
        sb.AppendLine();

        // ── Read results ──
        sb.AppendLine($"local count = readInteger(resBuf + 0x{RES_COUNT:X})");
        sb.AppendLine("if count == 0 then");
        sb.AppendLine("  print('[ZoltDump] No matching .NET managed objects found')");
        sb.AppendLine("  error('No matching .NET managed objects found')");
        sb.AppendLine("end");
        sb.AppendLine($"print(string.format('[ZoltDump] [%s] Found %d matching .NET managed objects', os.date('%H:%M:%S'), count))");
        sb.AppendLine();

        if (findAll)
        {
            // ── Multi-result: create CE memory records under a group header ──
            sb.AppendLine("-- ═══ Create memory records for all matches ═══");
            sb.AppendLine($"local parentName = '{EscapeLua(parentDesc)}'");
            sb.AppendLine($"local prefix = '{EscapeLua(symbolName)}'");
            sb.AppendLine("local addressList = getAddressList()");
            sb.AppendLine();
            sb.AppendLine("synchronize(function()");
            sb.AppendLine("  -- Find or create parent group header");
            sb.AppendLine("  local parentRecord = addressList.getMemoryRecordByDescription(parentName)");
            sb.AppendLine("  if not parentRecord then");
            sb.AppendLine("    parentRecord = addressList.createMemoryRecord()");
            sb.AppendLine("    parentRecord.Description = parentName");
            sb.AppendLine("    parentRecord.IsGroupHeader = true");
            sb.AppendLine("    parentRecord.Options = '[moHideChildren]'");
            sb.AppendLine("  end");
            sb.AppendLine();
            sb.AppendLine("  for i = 0, count - 1 do");
            sb.AppendLine($"    local entryBase = resBuf + 0x{RES_ENTRIES:X} + i * {RES_ENTRY_SIZE}");
            sb.AppendLine("    local objAddr = readQword(entryBase)");
            sb.AppendLine("    local managedAddr = readQword(entryBase + 8)");
            sb.AppendLine("    if managedAddr ~= 0 then");
            sb.AppendLine("      local addr = managedAddr + target_offset");
            sb.AppendLine("      local val = readInteger(addr) or 0");
            sb.AppendLine();
            sb.AppendLine("      -- Register symbol for programmatic access");
            sb.AppendLine("      local sym = string.format('%s_%d', prefix, i + 1)");
            sb.AppendLine("      unregisterSymbol(sym)");
            sb.AppendLine("      registerSymbol(sym, addr)");
            sb.AppendLine();
            sb.AppendLine("      -- Create CE memory record as child of parent group");
            sb.AppendLine("      local rec = addressList.createMemoryRecord()");
            sb.AppendLine($"      rec.Description = string.format('Instance[%d] +0x{targetOffset:X} (value=%d)', i + 1, val)");
            sb.AppendLine("      rec.Address = string.format('%X', addr)");
            sb.AppendLine("      rec.Vartype = vtDword");
            sb.AppendLine("      rec.Parent = parentRecord");
            sb.AppendLine("      rec.Color = (i % 2 == 0) and 0xFF8000 or 0x7F7F7F");
            sb.AppendLine();
            sb.AppendLine($"      print(string.format('[ZoltDump] [%s] %s = %X (value=%d, managed=%X)', os.date('%H:%M:%S'), sym, addr, val, managedAddr))");
            sb.AppendLine("    end");
            sb.AppendLine("  end");
            sb.AppendLine("end)");
            sb.AppendLine("closeLuaEngine()");
            sb.AppendLine();
            sb.AppendLine("[DISABLE]");
            sb.AppendLine("{$lua}");
            sb.AppendLine("if syntaxcheck then return end");
            sb.AppendLine();
            sb.AppendLine(EmitCloseLuaEngineDefInline());
            sb.AppendLine();
            sb.AppendLine($"local parentName = '{EscapeLua(parentDesc)}'");
            sb.AppendLine($"local prefix = '{EscapeLua(symbolName)}'");
            sb.AppendLine("local addressList = getAddressList()");
            sb.AppendLine();
            sb.AppendLine("-- Remove symbols");
            sb.AppendLine("for i = 1, 256 do");
            sb.AppendLine("  pcall(function() unregisterSymbol(string.format('%s_%d', prefix, i)) end)");
            sb.AppendLine("end");
            sb.AppendLine();
            sb.AppendLine("-- Remove all child memory records under the parent group");
            sb.AppendLine("synchronize(function()");
            sb.AppendLine("  local parentRecord = addressList.getMemoryRecordByDescription(parentName)");
            sb.AppendLine("  if parentRecord then");
            sb.AppendLine("    for i = addressList.Count - 1, 0, -1 do");
            sb.AppendLine("      local child = addressList[i]");
            sb.AppendLine("      if child.Parent == parentRecord then");
            sb.AppendLine("        child.delete()");
            sb.AppendLine("      end");
            sb.AppendLine("    end");
            sb.AppendLine("  end");
            sb.AppendLine("end)");
            sb.AppendLine($"print('[ZoltDump] All {symbolName}_* records removed')");
            sb.AppendLine("closeLuaEngine()");
        }
        else
        {
            // ── Single-result: register symbol + create memory record ──
            sb.AppendLine("-- ═══ Register symbol for first match ═══");
            sb.AppendLine($"local entryBase = resBuf + 0x{RES_ENTRIES:X}");
            sb.AppendLine("local managedAddr = readQword(entryBase + 8)");
            sb.AppendLine("local addr = managedAddr + target_offset");
            sb.AppendLine($"unregisterSymbol('{symbolName}')");
            sb.AppendLine($"registerSymbol('{symbolName}', addr)");
            sb.AppendLine($"print(string.format('[ZoltDump] {symbolName} = %X (managed @ %X)', addr, managedAddr))");
            sb.AppendLine();
            sb.AppendLine($"local recDesc = '{EscapeLua(className)} .NET managed +0x{targetOffset:X}'");
            sb.AppendLine("synchronize(function()");
            sb.AppendLine("  local al = getAddressList()");
            sb.AppendLine("  local rec = al.createMemoryRecord()");
            sb.AppendLine("  rec.Description = recDesc");
            sb.AppendLine("  rec.Address = string.format('%X', addr)");
            sb.AppendLine("  rec.Vartype = vtDword  -- C# int = 32-bit");
            sb.AppendLine("  rec.Color = 0xFF8000");
            sb.AppendLine("end)");
            sb.AppendLine("closeLuaEngine()");
            sb.AppendLine();
            sb.AppendLine("[DISABLE]");
            sb.AppendLine("{$lua}");
            sb.AppendLine("if syntaxcheck then return end");
            sb.AppendLine($"unregisterSymbol('{symbolName}')");
            sb.AppendLine($"print('[ZoltDump] {symbolName} symbol removed')");
            sb.AppendLine("closeLuaEngine()");
        }

        return sb.ToString();
    }

