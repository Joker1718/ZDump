using System.Text;

namespace ZoltDumpUI.Services;

/// <summary>
/// Generates CE Lua Auto Assembler scripts for dynamic address resolution
/// via the Qual mailbox (g_zoltMailbox exported from proxy DLL).
/// Scripts survive game restarts — they resolve by class + member name.
/// </summary>
public sealed class CeLuaScriptService
{
    // Mailbox struct field offsets (must match Qual.h MailboxData)
    private const int OFF_CMD          = 0x000;
    private const int OFF_STATUS       = 0x004;
    private const int OFF_RESULT       = 0x008;
    private const int OFF_MEMBER_INDEX = 0x00C;
    private const int OFF_OBJECT_ADDR  = 0x010;
    private const int OFF_MEMBER_ADDR  = 0x018;
    private const int OFF_MEMBER_TYPE  = 0x020;
    private const int OFF_CLASS_NAME   = 0x028;
    private const int OFF_MEMBER_NAME  = 0x128;
    private const int OFF_NODE_NAME    = 0x228;
    private const int OFF_ERROR_MSG    = 0x328;

    // Commands (must match Qual::Cmd)
    private const int CMD_IDLE             = 0;
    private const int CMD_FIND_INSTANCE    = 1;
    private const int CMD_GET_MEMBER_ADDR  = 2;
    private const int CMD_FIND_NODE        = 3;

    // Status (must match Qual::Status)
    private const int STATUS_IDLE       = 0;
    private const int STATUS_DONE       = 1;
    private const int STATUS_PROCESSING = 2;
    private const int STATUS_INIT       = 0xFF;

    /// <summary>
    /// Generate a CE Lua AA script that resolves a GDScript member address
    /// via the proxy DLL mailbox and registers it as a CE symbol.
    /// </summary>
    /// <param name="className">Godot class name (e.g. "Main")</param>
    /// <param name="memberName">GDScript member name (e.g. "JarMoney")</param>
    /// <param name="symbolName">CE symbol name to register (defaults to memberName)</param>
    /// <returns>Complete AA script with [ENABLE]/[DISABLE] sections</returns>
    public string GenerateMemberScript(string className, string memberName, string? symbolName = null)
    {
        symbolName ??= SanitizeSymbolName(memberName);

        var sb = new StringBuilder();
        sb.AppendLine("{$lua}");
        sb.AppendLine("[ENABLE]");
        sb.AppendLine($"-- ZoltDump: Resolve '{className}.{memberName}' via proxy DLL mailbox");
        sb.AppendLine($"-- Generated by ZoltDumpUI — survives game restarts");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        sb.AppendLine("local mb = getAddress('g_zoltMailbox')");
        sb.AppendLine("if mb == 0 or mb == nil then");
        sb.AppendLine("  print('[ZoltDump] ERROR: g_zoltMailbox not found — proxy DLL not loaded')");
        sb.AppendLine("  error('ZoltDumper proxy DLL not loaded')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"-- Wait for DLL init (STATUS_INIT = 0x{STATUS_INIT:X})");
        sb.AppendLine("for i = 1, 300 do  -- 30 second timeout");
        sb.AppendLine($"  if readInteger(mb + 0x{OFF_STATUS:X}) ~= 0x{STATUS_INIT:X} then break end");
        sb.AppendLine("  sleep(100)");
        sb.AppendLine("end");
        sb.AppendLine($"if readInteger(mb + 0x{OFF_STATUS:X}) == 0x{STATUS_INIT:X} then");
        sb.AppendLine("  error('ZoltDumper DLL init timeout')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("-- Write input fields (class name + member name)");
        sb.AppendLine($"writeString(mb + 0x{OFF_CLASS_NAME:X}, '{EscapeLua(className)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_CLASS_NAME:X} + {className.Length}, 0)  -- null terminator");
        sb.AppendLine($"writeString(mb + 0x{OFF_MEMBER_NAME:X}, '{EscapeLua(memberName)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_MEMBER_NAME:X} + {memberName.Length}, 0)  -- null terminator");
        sb.AppendLine();
        sb.AppendLine($"-- Clear previous result");
        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0)");
        sb.AppendLine($"writeQword(mb + 0x{OFF_MEMBER_ADDR:X}, 0)");
        sb.AppendLine();
        sb.AppendLine($"-- Trigger CMD_GET_MEMBER_ADDR (write cmd LAST)");
        sb.AppendLine($"writeInteger(mb + 0x{OFF_CMD:X}, {CMD_GET_MEMBER_ADDR})");
        sb.AppendLine();
        sb.AppendLine("-- Poll for completion (5 second timeout)");
        sb.AppendLine("for i = 1, 500 do");
        sb.AppendLine($"  local s = readInteger(mb + 0x{OFF_STATUS:X})");
        sb.AppendLine($"  if s == {STATUS_DONE} then break end");
        sb.AppendLine("  sleep(10)");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"local status = readInteger(mb + 0x{OFF_STATUS:X})");
        sb.AppendLine($"if status ~= {STATUS_DONE} then");
        sb.AppendLine("  error('ZoltDump mailbox timeout')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"local result = readInteger(mb + 0x{OFF_RESULT:X})");
        sb.AppendLine("if result ~= 0 then");
        sb.AppendLine($"  local errMsg = readString(mb + 0x{OFF_ERROR_MSG:X}, 256)");
        sb.AppendLine("  print('[ZoltDump] ERROR: ' .. errMsg)");
        sb.AppendLine("  error(errMsg)");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"local addr = readQword(mb + 0x{OFF_MEMBER_ADDR:X})");
        sb.AppendLine("if addr ~= 0 then");
        sb.AppendLine($"  unregisterSymbol('{symbolName}')");
        sb.AppendLine($"  registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"  print(string.format('[ZoltDump] {symbolName} = %X', addr))");
        sb.AppendLine("else");
        sb.AppendLine($"  print('[ZoltDump] WARNING: {memberName} address is 0')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");
        sb.AppendLine($"print('[ZoltDump] {symbolName} symbol removed')");

        return sb.ToString();
    }

    /// <summary>
    /// Generate a CE Lua AA script that finds an Object instance by class name.
    /// </summary>
    public string GenerateFindInstanceScript(string className, string? symbolName = null)
    {
        symbolName ??= SanitizeSymbolName(className);

        var sb = new StringBuilder();
        sb.AppendLine("{$lua}");
        sb.AppendLine("[ENABLE]");
        sb.AppendLine($"-- ZoltDump: Find instance of '{className}' via proxy DLL mailbox");
        sb.AppendLine();
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine();
        sb.AppendLine("local mb = getAddress('g_zoltMailbox')");
        sb.AppendLine("if mb == 0 or mb == nil then");
        sb.AppendLine("  error('ZoltDumper proxy DLL not loaded')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"-- Wait for DLL init");
        sb.AppendLine("for i = 1, 300 do");
        sb.AppendLine($"  if readInteger(mb + 0x{OFF_STATUS:X}) ~= 0x{STATUS_INIT:X} then break end");
        sb.AppendLine("  sleep(100)");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"writeString(mb + 0x{OFF_CLASS_NAME:X}, '{EscapeLua(className)}')");
        sb.AppendLine($"writeByte(mb + 0x{OFF_CLASS_NAME:X} + {className.Length}, 0)");
        sb.AppendLine($"writeQword(mb + 0x{OFF_OBJECT_ADDR:X}, 0)");
        sb.AppendLine($"writeInteger(mb + 0x{OFF_CMD:X}, {CMD_FIND_INSTANCE})");
        sb.AppendLine();
        sb.AppendLine("for i = 1, 500 do");
        sb.AppendLine($"  if readInteger(mb + 0x{OFF_STATUS:X}) == {STATUS_DONE} then break end");
        sb.AppendLine("  sleep(10)");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"if readInteger(mb + 0x{OFF_RESULT:X}) ~= 0 then");
        sb.AppendLine($"  error(readString(mb + 0x{OFF_ERROR_MSG:X}, 256))");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"local addr = readQword(mb + 0x{OFF_OBJECT_ADDR:X})");
        sb.AppendLine("if addr ~= 0 then");
        sb.AppendLine($"  unregisterSymbol('{symbolName}')");
        sb.AppendLine($"  registerSymbol('{symbolName}', addr)");
        sb.AppendLine($"  print(string.format('[ZoltDump] {symbolName} = %X', addr))");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine("[DISABLE]");
        sb.AppendLine($"{{$lua}}");
        sb.AppendLine("if syntaxcheck then return end");
        sb.AppendLine($"unregisterSymbol('{symbolName}')");

        return sb.ToString();
    }

    /// <summary>Sanitize a name for use as a CE symbol (alphanumeric + underscore only).</summary>
    private static string SanitizeSymbolName(string name)
    {
        var sb = new StringBuilder(name.Length);
        foreach (char c in name)
        {
            if (char.IsLetterOrDigit(c) || c == '_')
                sb.Append(c);
            else
                sb.Append('_');
        }
        return sb.Length > 0 ? sb.ToString() : "zolt_symbol";
    }

    /// <summary>Escape single quotes for Lua string literals.</summary>
    private static string EscapeLua(string s) => s.Replace("'", "\\'");
}
