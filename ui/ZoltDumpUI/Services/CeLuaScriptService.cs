    /// <summary>
    /// Emit closeLuaEngine() helper definition. Idempotent — only defines if not already present.
    /// Closes the CE Lua Engine window after a successful script run.
    /// </summary>
    private static void EmitCloseLuaEngineDef(StringBuilder sb)
    {
        sb.AppendLine("if not closeLuaEngine then");
        sb.AppendLine("    function closeLuaEngine()");
        sb.AppendLine("        synchronize(function()");
        sb.AppendLine("          getLuaEngine().Close()");
        sb.AppendLine("        end)");
        sb.AppendLine("    end");
        sb.AppendLine("    registerLuaFunctionHighlight('closeLuaEngine')");
        sb.AppendLine("end");
        sb.AppendLine();
    }

    /// <summary>
    /// Return closeLuaEngine definition as a string (for [DISABLE] sections that need
    /// it without an existing StringBuilder context from the [ENABLE] section).
    /// </summary>
    private static string EmitCloseLuaEngineDefInline()
    {
        var sb = new StringBuilder();
        EmitCloseLuaEngineDef(sb);
        return sb.ToString().TrimEnd();
    }

    /// <summary>Emit mailbox address resolution + DLL init wait.</summary>
    private void EmitMailboxInit(StringBuilder sb)
    {
        sb.AppendLine("local mb = getAddress('g_zoltMailbox')");
        sb.AppendLine("if mb == 0 or mb == nil then");
        sb.AppendLine("  print('[ZoltDump] ERROR: g_zoltMailbox not found — proxy DLL not loaded')");
        sb.AppendLine("  error('ZoltDumper proxy DLL not loaded')");
        sb.AppendLine("end");
        sb.AppendLine();
        sb.AppendLine($"-- Wait for DLL init (STATUS_INIT = 0x{STATUS_INIT:X})");
        sb.AppendLine("for i = 1, 300 do  -- 30 second timeout");
        sb.AppendLine($"  if readInteger(mb + 0x{OFF_STATUS:X}) ~= 0x{STATUS_INIT:X} then break end");
        sb.AppendLine("  sleep(100)");
        sb.AppendLine("end");
        sb.AppendLine($"if readInteger(mb + 0x{OFF_STATUS:X}) == 0x{STATUS_INIT:X} then");
        sb.AppendLine("  error('ZoltDumper DLL init timeout')");
        sb.AppendLine("end");
        sb.AppendLine();
    }

    /// <summary>
    /// Emit command trigger with status reset + polling loop + error check.
    /// IMPORTANT: Must reset status to IDLE before writing cmd, otherwise
    /// the poll loop sees stale STATUS_DONE from a previous command and
    /// returns immediately before the DLL processes the new command.
    /// </summary>
    private void EmitTriggerAndPoll(StringBuilder sb, int cmd, string cmdLabel,
        bool resultIsCount = false)
    {
        sb.AppendLine($"-- Reset status before triggering (avoid stale DONE from previous command)");
        sb.AppendLine($"writeInteger(mb + 0x{OFF_STATUS:X}, {STATUS_IDLE})");
        sb.AppendLine($"writeInteger(mb + 0x{OFF_RESULT:X}, 0)  -- clear previous error");
        sb.AppendLine($"writeInteger(mb + 0x{OFF_CMD:X}, {cmd})  -- trigger {cmdLabel}");
        sb.AppendLine();
        sb.AppendLine($"-- Poll for {cmdLabel} completion (15 second timeout)");
        sb.AppendLine("local _pollStart = os.clock()");
        sb.AppendLine("for i = 1, 1500 do");
        sb.AppendLine($"  if readInteger(mb + 0x{OFF_STATUS:X}) == {STATUS_DONE} then break end");
        sb.AppendLine("  sleep(10)");
        sb.AppendLine("end");
        sb.AppendLine($"local _elapsed = os.clock() - _pollStart");
        sb.AppendLine();
        sb.AppendLine($"if readInteger(mb + 0x{OFF_STATUS:X}) ~= {STATUS_DONE} then");
        sb.AppendLine($"  error(string.format('[ZoltDump] {cmdLabel} timeout after %.1fs', _elapsed))");
        sb.AppendLine("end");
        sb.AppendLine($"print(string.format('[ZoltDump] [%s] {cmdLabel} completed in %.2fs', os.date('%H:%M:%S'), _elapsed))");
        sb.AppendLine();
        if (resultIsCount)
        {
            // For bulk commands: result > 0 = match count (success), result < 0 = error code
            sb.AppendLine($"if readInteger(mb + 0x{OFF_RESULT:X}) < 0 then");
        }
        else
        {
            sb.AppendLine($"if readInteger(mb + 0x{OFF_RESULT:X}) ~= 0 then");
        }
        sb.AppendLine($"  local errMsg = readString(mb + 0x{OFF_ERROR_MSG:X}, 256)");
        sb.AppendLine("  print('[ZoltDump] ERROR: ' .. errMsg)");
        sb.AppendLine("  error(errMsg)");
        sb.AppendLine("end");
    }

    /// <summary>
    /// Emit Lua code that resolves .NET field names to offsets via CMD_RESOLVE_FIELD_OFFSET.
    /// Updates target_offset (and optionally filter_offset) in-place before the scan.
    /// Falls back to hardcoded offsets if resolution fails (e.g. DLL too old, Denken not loaded).
    /// </summary>
    private void EmitResolveFieldOffset(StringBuilder sb, string filterFieldName)
    {
        bool hasFilterField = !string.IsNullOrEmpty(filterFieldName);

        sb.AppendLine("-- ═══ Resolve .NET field offsets by name (survives game updates) ═══");
        sb.AppendLine("local function resolveField(typeName, fieldName)");
        sb.AppendLine("  -- Wait for mailbox idle");
        sb.AppendLine("  for i = 1, 100 do");
        sb.AppendLine($"    if readInteger(mb + 0x{OFF_STATUS:X}) == 0 then break end");
        sb.AppendLine("    sleep(10)");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine("  -- Write type name and field name");
        sb.AppendLine($"  writeString(mb + 0x{OFF_CLASS_NAME:X}, typeName)");
        sb.AppendLine($"  writeByte(mb + 0x{OFF_CLASS_NAME:X} + #typeName, 0)");
        sb.AppendLine($"  writeString(mb + 0x{OFF_MEMBER_NAME:X}, fieldName)");
        sb.AppendLine($"  writeByte(mb + 0x{OFF_MEMBER_NAME:X} + #fieldName, 0)");
        sb.AppendLine();
        sb.AppendLine($"  writeInteger(mb + 0x{OFF_STATUS:X}, 0)");
        sb.AppendLine($"  writeInteger(mb + 0x{OFF_RESULT:X}, 0)");
        sb.AppendLine($"  writeInteger(mb + 0x{OFF_CMD:X}, {CMD_RESOLVE_FIELD_OFFSET})");
        sb.AppendLine();
        sb.AppendLine("  for i = 1, 500 do  -- 5s timeout (first call may init Denken ~2s)");
        sb.AppendLine($"    if readInteger(mb + 0x{OFF_STATUS:X}) == 1 then break end");
        sb.AppendLine("    sleep(10)");
        sb.AppendLine("  end");
        sb.AppendLine();
        sb.AppendLine($"  if readInteger(mb + 0x{OFF_STATUS:X}) ~= 1 then return nil end");
        sb.AppendLine($"  local off = readInteger(mb + 0x{OFF_RESULT:X})");
        sb.AppendLine("  if off < 0 then return nil end");
        sb.AppendLine("  return off");
        sb.AppendLine("end");
        sb.AppendLine();

        // Resolve target field
        sb.AppendLine("if #dotnet_type > 0 and #target_field > 0 then");
        sb.AppendLine("  local _resolveStart = os.clock()");
        sb.AppendLine("  print(string.format('[ZoltDump] [%s] Resolving .NET field offsets for %s...', os.date('%H:%M:%S'), dotnet_type))");
        sb.AppendLine("  local resolved = resolveField(dotnet_type, target_field)");
        sb.AppendLine("  if resolved then");
        sb.AppendLine("    print(string.format('[ZoltDump] [%s] Resolved %s → 0x%X (was 0x%X)', os.date('%H:%M:%S'), target_field, resolved, target_offset))");
        sb.AppendLine("    target_offset = resolved");
        sb.AppendLine("  else");
        sb.AppendLine("    print(string.format('[ZoltDump] [%s] WARN: %s not resolved, using fallback 0x%X', os.date('%H:%M:%S'), target_field, target_offset))");
        sb.AppendLine("  end");

        // Resolve filter field
        if (hasFilterField)
        {
            sb.AppendLine("  if #filter_field > 0 and filter_offset >= 0 then");
            sb.AppendLine("    resolved = resolveField(dotnet_type, filter_field)");
            sb.AppendLine("    if resolved then");
            sb.AppendLine("      print(string.format('[ZoltDump] [%s] Resolved filter %s → 0x%X (was 0x%X)', os.date('%H:%M:%S'), filter_field, resolved, filter_offset))");
            sb.AppendLine("      filter_offset = resolved");
            sb.AppendLine("    else");
            sb.AppendLine("      print(string.format('[ZoltDump] [%s] WARN: filter %s not resolved, using fallback 0x%X', os.date('%H:%M:%S'), filter_field, filter_offset))");
            sb.AppendLine("    end");
            sb.AppendLine("  end");
        }

        sb.AppendLine("  print(string.format('[ZoltDump] [%s] Field resolution completed in %.2fs', os.date('%H:%M:%S'), os.clock() - _resolveStart))");
        sb.AppendLine("end");
        sb.AppendLine();
    }

